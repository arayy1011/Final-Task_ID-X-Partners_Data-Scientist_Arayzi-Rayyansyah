    # Confusion Matrix
    cm = confusion_matrix(y_test, y_predict)

    # Ekstrak nilai TP, FP, TN, FN dari confusion matrix
    TN, FP, FN, TP = cm.ravel()

    # Tampilkan nilai-nilai TP, FP, TN, FN
